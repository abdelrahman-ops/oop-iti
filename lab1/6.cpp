// 6. Program to make simple calculations (add, sub, multiply, divide) on two integers


#include <iostream>

using namespace std;

int main(){
    int x,y;
    cout << "Enter 1st number: " << endl;
    cin >> x ;
    cout << "Enter 2nd number: " << endl;
    cin >> y ;

    cout << "X + Y: " << x+y << endl;
    cout << "X - Y: " << x-y << endl;
    cout << "X * Y: " << x*y << endl;
    cout << "X / Y: " << x/y << endl;

    return 0;

}
